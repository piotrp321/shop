#!/bin/sh
# Writes the values file that tells Argo CD which images to deploy: the revision (the tag of the images) and the digest
# of each of the four images built by us. The same file is used by the smoke test of the workflow, by the render check
# and by the snapshot commit on the branch `deploy-images` (infra/k8s/environments/prod/values-images.yaml there), so
# what is tested is what is deployed.
#
# Usage: images-values.sh <commit sha> <output file>
# Environment: DIGEST_API, DIGEST_STORE, DIGEST_ADMIN, DIGEST_ELASTICSEARCH (sha256:<64 hex> each).
# The SHA must be a full lowercase commit SHA and every digest well formed, otherwise the script fails and writes
# nothing. The output depends only on the arguments and the digests: the same inputs give the same bytes.
set -eu

fail() {
  echo "images-values: $1" >&2
  exit "${2:-2}"
}

[ $# -eq 2 ] || fail "usage: images-values.sh <commit sha> <output file> (digests in DIGEST_API, DIGEST_STORE, DIGEST_ADMIN, DIGEST_ELASTICSEARCH)"
sha="$1"
out="$2"
case "$sha" in
  *[!0-9a-f]* | "") fail "'$sha' is not a full lowercase commit SHA" ;;
esac
[ "${#sha}" -eq 40 ] || fail "'$sha' is not a full commit SHA (40 hex digits)"

check_digest() {
  case "$2" in
    sha256:*[!0-9a-f]* | "") fail "$1 is not sha256:<64 hex digits> (got '$2')" ;;
    sha256:*) [ "${#2}" -eq 71 ] || fail "$1 is not sha256:<64 hex digits> (got '$2')" ;;
    *) fail "$1 is not sha256:<64 hex digits> (got '$2')" ;;
  esac
}
api="${DIGEST_API:-}"
store="${DIGEST_STORE:-}"
admin="${DIGEST_ADMIN:-}"
elasticsearch="${DIGEST_ELASTICSEARCH:-}"
check_digest DIGEST_API "$api"
check_digest DIGEST_STORE "$store"
check_digest DIGEST_ADMIN "$admin"
check_digest DIGEST_ELASTICSEARCH "$elasticsearch"

# Written aside and moved into place, so a failure never leaves a half-written file.
tmp="$(mktemp "$out.XXXXXX")" || fail "cannot write next to $out" 1
trap 'rm -f "$tmp"' EXIT
cat > "$tmp" <<VALUES
# Generated by infra/k8s/scripts/images-values.sh for the commit $sha. Do not edit.
image:
  tag: $sha
  digests:
    api: $api
    store: $store
    admin: $admin
    elasticsearch: $elasticsearch
VALUES
mv "$tmp" "$out"
trap - EXIT
